describe('configuração da aba 🧱Zagueiros', () => {
  it('preserva exatamente os 48 cabeçalhos brutos do FM26', () => {
    expect(zagueirosConfig.rawColumns).toEqual(RAW_COLUMNS)
  })

  it('expõe todas as 128 colunas numéricas de linha com os títulos da planilha', () => {
    expect(zagueirosConfig.metrics.map((item) => item.label)).toEqual(DERIVED_LABELS)
    expect(zagueirosConfig.metrics.map((item) => item.key)).toEqual(
      Object.keys(alanFrancoExpected),
    )
  })

  it('reproduz todas as fórmulas cacheadas da linha Alan Franco', () => {
    const player = derivePlayer(alanFrancoRaw, zagueirosConfig)
    expect(player).not.toBeNull()

    for (const [key, expected] of Object.entries(alanFrancoExpected)) {
      expect(Number(player?.[key]), key).toBeCloseTo(expected, 10)
    }
  })

  it('interpreta Presenças e replica os fallbacks e fatores de pênalti do Excel', () => {
    const player = derivePlayer({
      ...alanFrancoRaw,
      Minutos: '2790',
      Presenças: '31',
      HdJ: '0',
      Pens: '2',
      'Pens M': '1',
      xG: '3,00',
      Golos: '2',
    }, zagueirosConfig)

    expect(player).toMatchObject({
      jogosCompletos: 31,
      jogosTotais: 31,
      minPartida: 90,
      jogosComoTitular: 100,
      minPorHdJ: 5400,
      pensPerdidos: 1,
      pctConversaoPen: 50,
      npxG: 1.42,
    })
    expect(Number(player?.xgSemPenaltiRecalculado)).toBeCloseTo(-0.16, 10)
  })

  it('mantém Cabs como ganhos e Cab A como tentados, conforme as fórmulas da aba', () => {
    const player = derivePlayer(alanFrancoRaw, zagueirosConfig)

    expect(player).toMatchObject({
      cabsTentados: 193,
      cabsGanhos: 146,
      cabsPerdidos: 47,
      pctCabsGanhos: 75.64766839378238,
    })
  })
})
