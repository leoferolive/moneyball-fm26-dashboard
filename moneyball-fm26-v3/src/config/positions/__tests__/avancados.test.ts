describe('configuração da aba 🎯Avançados', () => {
  it('preserva exatamente os 50 cabeçalhos brutos do FM26', () => {
    expect(avancadosConfig.rawColumns).toEqual(RAW_COLUMNS)
  })

  it('expõe as 130 métricas numéricas na ordem e com os títulos da planilha', () => {
    expect(avancadosConfig.metrics.map((item) => item.label)).toEqual(DERIVED_LABELS)
    expect(avancadosConfig.metrics.map((item) => item.key)).toEqual(
      Object.keys(andreLuisExpected),
    )
  })

  it('reproduz todas as fórmulas cacheadas da linha André Luís', () => {
    const player = derivePlayer(andreLuisRaw, avancadosConfig)
    expect(player).not.toBeNull()

    for (const [key, expected] of Object.entries(andreLuisExpected)) {
      expect(Number(player?.[key]), key).toBeCloseTo(expected, 10)
    }
  })

  it('interpreta Presenças e replica os fallbacks explícitos do Excel', () => {
    const player = derivePlayer({
      ...andreLuisRaw,
      Minutos: '2790',
      Presenças: '31',
      HdJ: '0',
      Golos: '0',
      'Assist.': '0',
      Remates: '0',
      'Rem %': '0',
      Pens: '0',
      'Pens M': '0',
    }, avancadosConfig)

    expect(player).toMatchObject({
      jogosCompletos: 31,
      jogosTotais: 31,
      minPartida: 90,
      jogosComoTitular: 100,
      minHdj: 5000,
      pctPen: 0.001,
      minParaMarcar: 2790,
      minParaParticipar: 300,
    })
  })

  it('mantém cabeceios e cruzamentos nos campos exatos usados pela aba', () => {
    const player = derivePlayer({
      ...andreLuisRaw,
      'Cab A': '20',
      Cabs: '12',
      'CT-JA': '8',
      'CC-JA': '3',
      'Cr T': '13',
      'Cr C': '5',
    }, avancadosConfig)

    expect(player).toMatchObject({
      cabsDisp: 20,
      cabsG: 12,
      cabsPerd: 8,
      pctCabs: 60,
      cruzT: 8,
      cruzC: 3,
      tentsBP: 5,
      chancesBP: 2,
      pctBP: 40,
    })
  })
})
